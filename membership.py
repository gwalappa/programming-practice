#MEMBERSHIP OPERATOR
"""IN=returns true if the specified value found in the sequence
NOT IN=returns true if the seficified value is not found in the sequence"""
my_list=(1,2,3,4,5,6)
my_string="bhagyalakshmi"
print(3 in my_list)
print("bhagy" in my_string)
print(sum(my_list))
print(7 in my_list)
print("muttu" not in my_string)
print(8 not in my_list)